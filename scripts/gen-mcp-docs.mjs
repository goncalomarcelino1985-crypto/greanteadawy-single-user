// Generates docs/MCP.md from the live tool definitions: node scripts/gen-mcp-docs.mjs
import fs from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createMcpServer, GUIDE } from '../server/src/mcp/tools.js';

const server = createMcpServer(new Proxy({}, { get: () => async () => null }));
const [a, b] = InMemoryTransport.createLinkedPair();
await server.connect(a);
const client = new Client({ name: 'docs', version: '1' });
await client.connect(b);
const { tools } = await client.listTools();

const typeOf = (s) => {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((e) => `\`${e}\``).join(' \\| ');
  if (s.anyOf) return s.anyOf.map(typeOf).join(' \\| ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.type === 'object' && s.properties) return `{ ${Object.keys(s.properties).join(', ')} }`;
  return s.type || 'any';
};

let md = `# GreanTeaDawy MCP reference\n\n_Generated by \`node scripts/gen-mcp-docs.mjs\` — ${tools.length} tools._\n\n`;
md += GUIDE.replace(/^# .*\n/, '') + '\n## Tools\n\n';
for (const t of tools) {
  md += `### \`${t.name}\`\n\n${t.description}\n\n`;
  const props = t.inputSchema?.properties || {};
  const req = new Set(t.inputSchema?.required || []);
  if (Object.keys(props).length) {
    md += '| Parameter | Type | Required | Description |\n|---|---|---|---|\n';
    for (const [k, s] of Object.entries(props)) md += `| \`${k}\` | ${typeOf(s)} | ${req.has(k) ? 'yes' : ''} | ${(s.description || '').replace(/\|/g, '\\|')} |\n`;
    md += '\n';
  }
}
const { prompts } = await client.listPrompts();
md += '## Prompts\n\n' + prompts.map((p) => `- \`${p.name}\` — ${p.description} (args: ${(p.arguments || []).map((a) => a.name).join(', ')})`).join('\n') + '\n';
const { resources } = await client.listResources();
md += '\n## Resources\n\n' + resources.map((r) => `- \`${r.uri}\` — ${r.description}`).join('\n') + '\n';
fs.writeFileSync(new URL('../docs/MCP.md', import.meta.url), md);
console.log(`wrote docs/MCP.md (${tools.length} tools)`);
await client.close();
